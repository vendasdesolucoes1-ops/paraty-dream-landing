-- Metas e relatórios de conversão por etapa e por vendedor (issue #59).
--
-- Três peças:
--   1. leads_etapas_historico — o histórico estruturado de mudanças de etapa.
--      As interações guardam o movimento como texto livre ("Status alterado
--      manualmente para Proposta…"), e as Edge Functions mudam a etapa sem
--      registrar nada parseável. Sem histórico não há taxa de conversão nem
--      tempo por etapa: um trigger em leads passa a registrar toda mudança de
--      status_crm, venha do painel, da Sophia ou de qualquer função.
--      O passado é reconstruído uma única vez (aproximado) a partir das
--      interações, das visitas e do status atual.
--   2. metas — alvo por vendedor (ou da equipe, vendedor_id nulo) e período.
--   3. Funções de relatório (SECURITY DEFINER, recortadas pelo papel: gestão
--      vê todos; vendedor só a própria carteira), sempre sem leads de teste e
--      sem leads na lixeira.
--
-- Datas dos filtros são dias do calendário de Brasília.

-- ---------------------------------------------------------------------------
-- Ordem das etapas do funil (perdido não avança o funil: 0)
-- ---------------------------------------------------------------------------
create or replace function public.etapa_ordem(p_status text)
returns integer
language sql
immutable
set search_path = public
as $$
  select case p_status
    when 'novo' then 1
    when 'qualificado' then 2
    when 'agendado' then 3
    when 'visitou' then 4
    when 'proposta' then 5
    when 'fechado' then 6
    else 0
  end
$$;

-- Início (inclusive) do dia p_dia no fuso de Brasília, como timestamptz.
create or replace function public.inicio_do_dia_brt(p_dia date)
returns timestamptz
language sql
immutable
set search_path = public
as $$
  select p_dia::timestamp at time zone 'America/Sao_Paulo'
$$;

grant execute on function public.etapa_ordem(text) to authenticated;
grant execute on function public.inicio_do_dia_brt(date) to authenticated;

