create table if not exists public.metas (
  id             uuid primary key default gen_random_uuid(),
  -- Nulo = meta da equipe inteira.
  vendedor_id    uuid references public.vendedores(id) on delete cascade,
  periodo_inicio date not null,
  periodo_fim    date not null,
  indicador      text not null
                 check (indicador in ('leads_atendidos', 'visitas', 'propostas', 'vendas')),
  alvo           numeric not null check (alvo > 0),
  criado_por     uuid default auth.uid(),
  criado_em      timestamptz not null default now(),
  constraint metas_periodo_valido check (periodo_fim >= periodo_inicio)
);

-- Uma meta por vendedor (ou equipe), indicador e período.
create unique index if not exists metas_unica_idx
  on public.metas (
    coalesce(vendedor_id, '00000000-0000-0000-0000-000000000000'::uuid),
    indicador, periodo_inicio, periodo_fim
  );
create index if not exists metas_periodo_idx on public.metas (periodo_inicio, periodo_fim);

comment on table public.metas is
  'Metas por vendedor (vendedor_id) ou da equipe (vendedor_id nulo) num período. Indicadores: leads_atendidos, visitas, propostas, vendas.';

alter table public.metas enable row level security;

drop policy if exists "metas_select_por_papel" on public.metas;
