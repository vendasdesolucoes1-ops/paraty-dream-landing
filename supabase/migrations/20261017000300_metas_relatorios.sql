create table if not exists public.leads_etapas_historico (
  id              bigint generated by default as identity primary key,
  lead_id         uuid not null references public.leads(id) on delete cascade,
  status_anterior text,
  status_novo     text not null,
  mudou_em        timestamptz not null default now(),
  alterado_por    uuid,
  -- 'trigger' = registrado na hora; 'reconstruido' = inferido do passado.
  origem_registro text not null default 'trigger'
                  check (origem_registro in ('trigger', 'reconstruido'))
);

create index if not exists leads_etapas_historico_lead_idx
  on public.leads_etapas_historico (lead_id, mudou_em);
create index if not exists leads_etapas_historico_status_idx
  on public.leads_etapas_historico (status_novo, mudou_em);

comment on table public.leads_etapas_historico is
  'Mudanças de etapa (status_crm) dos leads, gravadas por trigger. Base dos relatórios de conversão e de tempo por etapa.';

alter table public.leads_etapas_historico enable row level security;

-- Só leitura pelo painel, com o mesmo recorte dos leads. Quem escreve é o
-- trigger (SECURITY DEFINER).
drop policy if exists "leads_etapas_historico_select" on public.leads_etapas_historico;
create policy "leads_etapas_historico_select" on public.leads_etapas_historico
  for select to authenticated
  using (public.pode_ver_lead(lead_id));

revoke all on public.leads_etapas_historico from anon;
revoke insert, update, delete on public.leads_etapas_historico from authenticated;
grant select on public.leads_etapas_historico to authenticated;

-- Reconstrução do passado: roda uma vez só, enquanto a tabela está vazia
-- (antes do trigger existir). É aproximada:
--   • todo lead começa em "novo" na data de criação;
--   • "Status alterado manualmente para X" (Kanban) vira mudança para X;
--   • a interação de qualificação da Sophia vira "qualificado";
--   • visita criada vira "agendado"; visita realizada vira "visitou";
--   • se a última etapa inferida não for a atual, a atual entra no fim.
do $$
begin
  if exists (select 1 from public.leads_etapas_historico) then
    return;
  end if;

  with eventos as (
    select l.id as lead_id, 'novo'::text as status, l.created_at as quando
      from public.leads l
    union all
    select i.lead_id,
           lower(substring(i.conteudo from '^Status alterado manualmente para (\S+)')),
           i.created_at
      from public.interacoes i
     where i.lead_id is not null
       and i.conteudo like 'Status alterado manualmente para %'
    union all
    select i.lead_id, 'qualificado', i.created_at
      from public.interacoes i
     where i.lead_id is not null and i.canal = 'qualificacao'
    union all
    select v.lead_id, 'agendado', coalesce(v.created_at, v.data_hora)
      from public.visitas v
     where v.lead_id is not null
    union all
    select v.lead_id, 'visitou', v.data_hora
      from public.visitas v
     where v.lead_id is not null and v.status = 'realizada'
  ),
  validos as (
    select e.*
      from eventos e
      join public.leads l on l.id = e.lead_id
     where e.status in ('novo', 'qualificado', 'agendado', 'visitou', 'proposta', 'fechado', 'perdido')
       and e.quando is not null
  ),
  ordenados as (
    select v.*, lag(v.status) over (partition by v.lead_id order by v.quando) as anterior
      from validos v
  )
  insert into public.leads_etapas_historico
    (lead_id, status_anterior, status_novo, mudou_em, origem_registro)
  select lead_id, anterior, status, quando, 'reconstruido'
    from ordenados
   where anterior is distinct from status;

  -- Fecha com a etapa atual quando ela não é a última inferida.
  insert into public.leads_etapas_historico
    (lead_id, status_anterior, status_novo, mudou_em, origem_registro)
  select l.id, ult.status_novo, l.status_crm,
         greatest(l.updated_at, ult.mudou_em), 'reconstruido'
    from public.leads l
    join lateral (
      select h.status_novo, h.mudou_em
        from public.leads_etapas_historico h
       where h.lead_id = l.id
       order by h.mudou_em desc, h.id desc
       limit 1
    ) ult on true
   where ult.status_novo is distinct from l.status_crm;
end;
$$;

create or replace function public.registrar_etapa_lead()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_op = 'INSERT' then
    insert into public.leads_etapas_historico (lead_id, status_anterior, status_novo, mudou_em, alterado_por)
    values (new.id, null, new.status_crm, coalesce(new.created_at, now()), auth.uid());
  elsif new.status_crm is distinct from old.status_crm then
    insert into public.leads_etapas_historico (lead_id, status_anterior, status_novo, mudou_em, alterado_por)
    values (new.id, old.status_crm, new.status_crm, now(), auth.uid());
  end if;
  return null;
end;
$$;

revoke all on function public.registrar_etapa_lead() from public, anon, authenticated;

drop trigger if exists trg_leads_registrar_etapa on public.leads;
create trigger trg_leads_registrar_etapa
  after insert or update of status_crm on public.leads
  for each row execute function public.registrar_etapa_lead();

