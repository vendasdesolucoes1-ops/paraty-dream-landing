-- Funil de conversão da safra de leads que entrou no período: quantos
-- chegaram a cada etapa (o ponto mais longe a que o lead chegou, pelo
-- histórico, pelas visitas e pelo status atual) e as taxas entre etapas.
-- Uma linha de total, uma por vendedor e uma por origem.
drop function if exists public.relatorio_conversao(date, date);
create function public.relatorio_conversao(p_inicio date, p_fim date)
returns table (
  dimensao          text,
  chave             text,
  rotulo            text,
  entraram          integer,
  qualificados      integer,
  agendados         integer,
  visitaram         integer,
  propostas         integer,
  fechados          integer,
  perdidos          integer,
  taxa_qualificacao numeric,
  taxa_agendamento  numeric,
  taxa_visita       numeric,
  taxa_proposta     numeric,
  taxa_fechamento   numeric,
  taxa_geral        numeric
)
language sql
stable
security definer
set search_path = public
as $$
  with safra as (
    select l.id, l.vendedor_id, l.origem, l.status_crm
      from public.leads l
     where not l.is_teste
       and l.deletado_em is null
       and l.created_at >= public.inicio_do_dia_brt(p_inicio)
       and l.created_at < public.inicio_do_dia_brt(p_fim + 1)
       and (public.sou_gestao() or l.vendedor_id = public.meu_vendedor_id())
  ),
  alcance as (
    select s.id, s.vendedor_id, s.origem, s.status_crm,
           greatest(
             1,
             public.etapa_ordem(s.status_crm),
             coalesce((
               select max(public.etapa_ordem(h.status_novo))
                 from public.leads_etapas_historico h
                where h.lead_id = s.id
             ), 0),
             coalesce((
               select max(case when v.status = 'realizada' then 4 else 3 end)
                 from public.visitas v
                where v.lead_id = s.id
             ), 0)
           ) as ordem_max
      from safra s
  ),
  agregado as (
    select case
             when grouping(a.vendedor_id) = 0 then 'vendedor'
             when grouping(a.origem) = 0 then 'origem'
             else 'total'
           end as dimensao,
           case
             when grouping(a.vendedor_id) = 0 then coalesce(a.vendedor_id::text, 'sem_vendedor')
             when grouping(a.origem) = 0 then coalesce(a.origem, 'sem_origem')
             else 'total'
           end as chave,
           case
             when grouping(a.vendedor_id) = 0 then coalesce(max(vd.nome), 'Sem vendedor')
             when grouping(a.origem) = 0 then coalesce(a.origem, 'Sem origem')
             else 'Total'
           end as rotulo,
           count(*)::integer as entraram,
           count(*) filter (where a.ordem_max >= 2)::integer as qualificados,
           count(*) filter (where a.ordem_max >= 3)::integer as agendados,
           count(*) filter (where a.ordem_max >= 4)::integer as visitaram,
           count(*) filter (where a.ordem_max >= 5)::integer as propostas,
           count(*) filter (where a.ordem_max >= 6)::integer as fechados,
           count(*) filter (where a.status_crm = 'perdido')::integer as perdidos
      from alcance a
      left join public.vendedores vd on vd.id = a.vendedor_id
     group by grouping sets ((), (a.vendedor_id), (a.origem))
  )
  select g.dimensao, g.chave, g.rotulo,
         g.entraram, g.qualificados, g.agendados, g.visitaram, g.propostas, g.fechados, g.perdidos,
         round(g.qualificados::numeric / nullif(g.entraram, 0), 4),
         round(g.agendados::numeric / nullif(g.qualificados, 0), 4),
         round(g.visitaram::numeric / nullif(g.agendados, 0), 4),
         round(g.propostas::numeric / nullif(g.visitaram, 0), 4),
         round(g.fechados::numeric / nullif(g.propostas, 0), 4),
         round(g.fechados::numeric / nullif(g.entraram, 0), 4)
    from agregado g
   order by case g.dimensao when 'total' then 0 when 'vendedor' then 1 else 2 end,
            g.entraram desc, g.rotulo
$$;

-- Tempo médio em cada etapa ativa do funil, para as passagens que começaram
-- no período. Passagem concluída = o lead já saiu da etapa; as que seguem
-- abertas aparecem à parte (em_andamento), com o tempo acumulado até agora.
drop function if exists public.relatorio_tempo_por_etapa(date, date);
create function public.relatorio_tempo_por_etapa(p_inicio date, p_fim date)
returns table (
  etapa                    text,
  ordem                    integer,
  passagens                integer,
  media_horas              numeric,
  mediana_horas            numeric,
  em_andamento             integer,
  media_horas_em_andamento numeric
)
language sql
stable
security definer
set search_path = public
as $$
  with carteira as (
    select l.id
      from public.leads l
     where not l.is_teste
       and l.deletado_em is null
       and (public.sou_gestao() or l.vendedor_id = public.meu_vendedor_id())
  ),
  marcados as (
    select h.id, h.lead_id, h.status_novo, h.mudou_em,
           lag(h.status_novo) over (partition by h.lead_id order by h.mudou_em, h.id) as anterior
      from public.leads_etapas_historico h
      join carteira c on c.id = h.lead_id
  ),
  passagens as (
    select m.status_novo as etapa, m.mudou_em as entrou_em,
           lead(m.mudou_em) over (partition by m.lead_id order by m.mudou_em, m.id) as saiu_em
      from marcados m
     where m.anterior is distinct from m.status_novo
  ),
  no_periodo as (
    select p.etapa,
           extract(epoch from (p.saiu_em - p.entrou_em)) / 3600.0 as horas,
           extract(epoch from (now() - p.entrou_em)) / 3600.0 as horas_abertas,
           p.saiu_em is null as aberta
      from passagens p
     where p.entrou_em >= public.inicio_do_dia_brt(p_inicio)
       and p.entrou_em < public.inicio_do_dia_brt(p_fim + 1)
  ),
  etapas(etapa, ordem) as (
    values ('novo', 1), ('qualificado', 2), ('agendado', 3), ('visitou', 4), ('proposta', 5)
  )
  select e.etapa, e.ordem,
         count(n.etapa) filter (where not n.aberta)::integer,
         round((avg(n.horas) filter (where not n.aberta))::numeric, 1),
         round((percentile_cont(0.5) within group (order by n.horas)
                 filter (where not n.aberta))::numeric, 1),
         count(n.etapa) filter (where n.aberta)::integer,
         round((avg(n.horas_abertas) filter (where n.aberta))::numeric, 1)
    from etapas e
    left join no_periodo n on n.etapa = e.etapa
   group by e.etapa, e.ordem
   order by e.ordem
$$;

-- Realizado de um indicador num período, para um vendedor ou para a equipe
-- (p_vendedor nulo). Uso interno de metas_x_realizado: não é exposta ao
-- painel, porque não recorta pelo papel.
create or replace function public.realizado_do_indicador(
  p_indicador text,
  p_vendedor  uuid,
  p_inicio    date,
  p_fim       date
)
returns numeric
language sql
stable
security definer
set search_path = public
as $$
  select case p_indicador
    when 'leads_atendidos' then (
      select count(*)
        from public.leads l
       where not l.is_teste and l.deletado_em is null
         and l.created_at >= public.inicio_do_dia_brt(p_inicio)
         and l.created_at < public.inicio_do_dia_brt(p_fim + 1)
         and (p_vendedor is null or l.vendedor_id = p_vendedor)
    )
    when 'visitas' then (
      select count(*)
        from public.visitas v
        join public.leads l on l.id = v.lead_id
       where v.status = 'realizada'
         and not l.is_teste and l.deletado_em is null
         and v.data_hora >= public.inicio_do_dia_brt(p_inicio)
         and v.data_hora < public.inicio_do_dia_brt(p_fim + 1)
         and (p_vendedor is null or coalesce(v.vendedor_id, l.vendedor_id) = p_vendedor)
    )
    when 'propostas' then (
      select count(distinct h.lead_id)
        from public.leads_etapas_historico h
        join public.leads l on l.id = h.lead_id
       where h.status_novo = 'proposta'
         and not l.is_teste and l.deletado_em is null
         and h.mudou_em >= public.inicio_do_dia_brt(p_inicio)
         and h.mudou_em < public.inicio_do_dia_brt(p_fim + 1)
         and (p_vendedor is null or l.vendedor_id = p_vendedor)
    )
    when 'vendas' then (
      select count(distinct h.lead_id)
        from public.leads_etapas_historico h
        join public.leads l on l.id = h.lead_id
       where h.status_novo = 'fechado'
         and not l.is_teste and l.deletado_em is null
         and h.mudou_em >= public.inicio_do_dia_brt(p_inicio)
         and h.mudou_em < public.inicio_do_dia_brt(p_fim + 1)
         and (p_vendedor is null or l.vendedor_id = p_vendedor)
    )
  end::numeric
$$;

revoke all on function public.realizado_do_indicador(text, uuid, date, date)
  from public, anon, authenticated;

-- Metas que tocam o período, com o realizado medido no período da própria
-- meta. Gestão vê todas; vendedor vê as dele e as da equipe (o realizado da
-- equipe é o total do time — só números, nenhum lead de outra carteira).
drop function if exists public.metas_x_realizado(date, date);
create function public.metas_x_realizado(p_inicio date, p_fim date)
returns table (
  meta_id           uuid,
  vendedor_id       uuid,
  vendedor_nome     text,
  indicador         text,
  periodo_inicio    date,
  periodo_fim       date,
  alvo              numeric,
  realizado         numeric,
  percentual        numeric,
  periodo_decorrido numeric
)
language sql
stable
security definer
set search_path = public
as $$
  select m.id, m.vendedor_id, vd.nome, m.indicador, m.periodo_inicio, m.periodo_fim, m.alvo,
         r.valor,
         round(r.valor / nullif(m.alvo, 0), 4),
         round(
           least(1, greatest(0,
             ((now() at time zone 'America/Sao_Paulo')::date - m.periodo_inicio + 1)::numeric
             / (m.periodo_fim - m.periodo_inicio + 1)
           )),
           4
         )
    from public.metas m
    left join public.vendedores vd on vd.id = m.vendedor_id
    cross join lateral (
      select coalesce(
        public.realizado_do_indicador(m.indicador, m.vendedor_id, m.periodo_inicio, m.periodo_fim),
        0
      ) as valor
    ) r
   where m.periodo_inicio <= p_fim
     and m.periodo_fim >= p_inicio
     and (
       public.sou_gestao()
       or m.vendedor_id is null
       or m.vendedor_id = public.meu_vendedor_id()
     )
   order by m.vendedor_id nulls first, vd.nome, m.indicador, m.periodo_inicio
$$;

revoke all on function public.relatorio_conversao(date, date) from public, anon;
revoke all on function public.relatorio_tempo_por_etapa(date, date) from public, anon;
revoke all on function public.metas_x_realizado(date, date) from public, anon;
grant execute on function public.relatorio_conversao(date, date) to authenticated;
grant execute on function public.relatorio_tempo_por_etapa(date, date) to authenticated;
grant execute on function public.metas_x_realizado(date, date) to authenticated;

